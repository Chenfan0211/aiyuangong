-- 门店运营系统 · 权威数据模型（PostgreSQL 16+）
--
-- 本文件分两部分：
--   A. 已落地：与运行时代码（platform_data.py / store_ops_data.py / task_store.py / auth.py）逐一对应，
--      PostgreSQL 16.2 建表并完成 SQLite → PG 数据迁移验证（见 pg_sync.py）。
--   B. 规划中：原设计里面向后续批次（审批中心、平台连接器、指标长表）的表，仍未接线，勿在生产启用。
--
-- 统一约定：
--   * 除全局表（login_attempts）外，**每张表都带 tenant_id**；门店级数据带 store_id，隔离不依赖前端参数；
--   * jsonb 列名沿用运行时命名（target_json / evidence_required_json / before_json / after_json），
--     以便同一份业务 SQL 在两个引擎上跑（批次 8b）；
--   * 指向 stores 的外键**暂缓**：门店注册表当前仍由 store_config.json 承载，运行时先写数据后写注册表，
--     强制外键会让导入失败；租户/门店列的索引与校验已就位，注册表管理随门店管理批次补齐；
--   * 金额用 numeric(12,2)、评分用 numeric(2,1)、时间用 timestamptz、结构化字段用 jsonb；
--   * 所有 DDL 幂等（create ... if not exists），可由 pg_sync.py 重复执行。

-- ============================================================
-- A0. 迁移记录
-- ============================================================
-- 由 pg_sync.py migrate 维护：版本账本 + 持锁记录（数据库 advisory lock 的可见副本）。
-- init 同样创建这两张表，但只有 `migrate --apply` 才写入版本行；这两张表不带 tenant_id，
-- 属于迁移基础设施而非门店业务数据，不参与 RLS。
create table if not exists schema_migrations (
  version integer primary key,
  name text not null,
  checksum text not null,
  applied_at timestamptz not null default now(),
  adopted boolean not null default false,
  applied_by text not null default current_user
);

create table if not exists schema_migration_lock (
  lock_key bigint primary key,
  locked_by text not null,
  locked_at timestamptz not null default now(),
  released_at timestamptz
);
